const GLYPH_W = 5;
const GLYPH_H = 7;
/** At most this many characters are drawn. */
export const PIXEL_TEXT_MAX = 8;
/** Height of a drawn text in font pixels: a glyph and its outline above and below. */
export const PIXEL_FONT_HEIGHT = GLYPH_H + 2;

/** A drawn text: `cells[y * width + x]` is 0 (empty), 1 (outline) or 2 (fill); row 0 is the top. */
export interface PixelText {
  width: number;
  height: number;
  cells: Uint8Array;
}

/**
 * `text` (upper-cased; unknown characters become '?'; at most PIXEL_TEXT_MAX of them) in the
 * pixel font, one empty column between glyphs, with an outline round every lit pixel.
 */
export function pixelText(text: string): PixelText {
  const chars = [...text.toUpperCase()].slice(0, PIXEL_TEXT_MAX);
  const width = Math.max(1, chars.length * (GLYPH_W + 1) - 1) + 2;
  const height = PIXEL_FONT_HEIGHT;
  const cells = new Uint8Array(width * height);
  chars.forEach((ch, n) => {
    const glyph = GLYPHS[ch] ?? (GLYPHS['?'] as string[]);
    const x0 = 1 + n * (GLYPH_W + 1);
    for (let y = 0; y < GLYPH_H; y++) {
      const row = glyph[y] as string;
      for (let x = 0; x < GLYPH_W; x++) if (row[x] === '#') cells[(y + 1) * width + x0 + x] = 2;
    }
  });
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      if (cells[y * width + x] !== 2) continue;
      for (let dy = -1; dy <= 1; dy++) {
        for (let dx = -1; dx <= 1; dx++) {
          const i = (y + dy) * width + (x + dx);
          if (cells[i] === 0) cells[i] = 1;
        }
      }
    }
  }
  return { width, height, cells };
}
